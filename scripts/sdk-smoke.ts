import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const started = performance.now();
const log = (step: string): void => console.log(`${Math.round(performance.now() - started)} ms ${step}`);
log('importing SDK');
const { createAgentSession, DefaultResourceLoader, ModelRuntime, SessionManager, SettingsManager } = await import('@earendil-works/pi-coding-agent');
log('SDK imported');
const root = await mkdtemp(path.join(tmpdir(), 'tinycode-sdk-'));
const runtime = await ModelRuntime.create({ authPath: path.join(root, 'auth.json'), modelsPath: null, modelsStorePath: path.join(root, 'models.json'), refreshOnCreate: false, allowModelNetwork: false });
log('model runtime created');
const settingsManager = SettingsManager.inMemory({ retry: { enabled: false, provider: { maxRetries: 0 } }, compaction: { enabled: false }, enableAnalytics: false, enableInstallTelemetry: false });
const loader = new DefaultResourceLoader({ cwd: root, agentDir: root, settingsManager, noExtensions: true, noSkills: true, noThemes: true, noPromptTemplates: true, noContextFiles: true, systemPromptOverride: () => 'Return JSON', appendSystemPromptOverride: () => [] });
await loader.reload(); log('resources loaded');
const model = runtime.getModels('openai')[0];
const { session } = await createAgentSession({ cwd: root, agentDir: root, modelRuntime: runtime, ...(model ? { model } : {}), noTools: 'all', settingsManager, resourceLoader: loader, sessionManager: SessionManager.inMemory(root) });
log('session assembled');
console.log(`Active tools: ${session.getActiveToolNames().length}`);
await session.abort(); session.dispose(); log('abort/dispose complete');
